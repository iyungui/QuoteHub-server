// utils/nicknameGenerator.js
// 외부 API 의존 없이 로컬에서 한글 닉네임을 생성한다.
// "형용사 + 명사" 조합으로 자연스러운 랜덤 닉네임을 만든다.
// (예: 행복한고양이, 용감한너구리)

const ADJECTIVES = [
  "행복한", "용감한", "따뜻한", "지혜로운", "명랑한", "씩씩한", "차분한",
  "상냥한", "부지런한", "엉뚱한", "자유로운", "다정한", "발랄한", "든든한",
  "신비한", "온화한", "재빠른", "우아한", "활기찬", "느긋한", "반짝이는",
  "포근한", "청량한", "정직한", "유쾌한", "고요한", "빛나는", "슬기로운",
  "싱그러운", "정겨운",
];

const NOUNS = [
  "고양이", "강아지", "여우", "너구리", "토끼", "사슴", "다람쥐", "판다",
  "펭귄", "수달", "고래", "돌고래", "부엉이", "참새", "고슴도치", "햄스터",
  "알파카", "코알라", "나무늘보", "두더지", "오리", "백조", "청설모", "반달곰",
  "물개", "북극곰", "치타", "기린", "얼룩말", "카피바라",
];

const pick = (arr) => arr[Math.floor(Math.random() * arr.length)];

/**
 * "형용사 + 명사" 조합의 닉네임 후보 하나를 생성한다.
 * @returns {string}
 */
const generateNicknameCandidate = () => `${pick(ADJECTIVES)}${pick(NOUNS)}`;

module.exports = {
  generateNicknameCandidate,
  ADJECTIVES,
  NOUNS,
};
